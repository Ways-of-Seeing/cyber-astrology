# ── Helper functions ─────────────────────────────────────────────────────────

def get(planet_key: str, sign_key: str, lang: str = "pt") -> dict | None:
    """
    Retrieve interpretation for a given planet/point and sign.
    planet_key: 'sun', 'moon', 'ascendant', 'mercury', etc.
    sign_key:   'aries', 'taurus', etc.
    lang:       'pt' or 'en'
    """
    key = f"{planet_key}_{sign_key}"
    entry = PLANET_IN_SIGN.get(key)
    if entry:
        return entry.get(lang, entry.get("pt"))
    return None
